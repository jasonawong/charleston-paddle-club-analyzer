// Produce a dependency-free classic script that also works on file:// pages.
import { readFile, writeFile } from 'node:fs/promises';
const read = name => readFile(new URL(name, import.meta.url), 'utf8');
const [model, app, gpx, conditionsText] = await Promise.all([
  read('model.js'), read('app.js'), read('assets/pl-2026-10-24.gpx'), read('assets/conditions.json')
]);
const appBody = app.replace(/^import [^\n]+ from '\.\/model\.js';\r?\n/, '');
if (appBody === app) throw new Error('The expected model import was not found; update the browser bundle builder.');
const payload = JSON.stringify({ gpx, conditions: JSON.parse(conditionsText) });
const bundle = '// Generated by node build.mjs. Edit app.js / model.js, then rebuild.\n(function () {\n\'use strict\';\nconst embeddedRace = ' + payload + ';\n' + model.replace(/^export /gm, '') + '\n' + appBody + '\n})();\n';
await writeFile(new URL('app.bundle.js', import.meta.url), bundle);
console.log('Built app.bundle.js with the bundled race and conditions; no module loader or startup file requests needed.');

// Produce a dependency-free classic script that also works on file:// pages.
import { readFile, writeFile } from 'node:fs/promises';
const read = name => readFile(new URL(name, import.meta.url), 'utf8');
const [gpx, women] = await Promise.all([read('assets/pl-2026-10-24.gpx'), read('assets/cpc-women-chattajack-2026.gpx')]);
async function bundle(output, files, payloadName, payload) {
  const bodies = await Promise.all(files.map(read));
  const source = bodies.map(body => body.replace(/^import [^\n]+ from '\.\/[^']+';\r?\n/gm, '').replace(/^export /gm, '')).join('\n');
  if (/^import |^export /m.test(source)) throw new Error('Unresolved module declaration in ' + output);
  await writeFile(new URL(output, import.meta.url), '// Generated by node build.mjs. Edit source files, then rebuild.\n(function () {\n\'use strict\';\nconst ' + payloadName + ' = ' + JSON.stringify(payload) + ';\n' + source + '\n})();\n');
}
await bundle('app.bundle.js', ['model.js', 'gpx.js', 'palmetto.js', 'app.js'], 'embeddedRace', { men: gpx, women });
await bundle('head-to-head.bundle.js', ['model.js', 'gpx.js', 'palmetto.js', 'comparison-model.js', 'head-to-head.js'], 'embeddedComparison', { men: gpx, women });
console.log('Built both classic browser bundles with embedded GPX recordings.');
